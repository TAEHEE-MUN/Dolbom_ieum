import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('http://127.0.0.1:8000');
await page.getByRole('heading',{name:'휴대전화로 로그인'}).waitFor();
mkdirSync('docs/screenshots',{recursive:true});
await page.screenshot({path:'docs/screenshots/admin-login.png',fullPage:true});
const visit={id:'v1',recipient_id:'r1',worker_id:'w1',state:'ended',last_received_at:new Date().toISOString()};
await page.route('**/api/bootstrap',route=>route.fulfill({json:{user_id:'a1',profile:{id:'a1',name:'테스트 관리자'},membership:{role:'admin'},agencies:[{name:'가상 시험 기관'}],recipients:[{id:'r1',name:'테스트 이용자',address:'가상 주소'}],staff:[{id:'w1',name:'테스트 지원사'}],memberships:[{user_id:'w1',role:'worker'}],visits:[visit],schedules:[],cases:[],corrections:[]}}));
await page.route('**/api/visits/v1',route=>route.fulfill({json:{visit,summary:{total_seconds:16200,care_seconds:14400,break_seconds:1800},visit_events:[{seq:1,kind:'start',occurred_at:'2026-11-20T00:00:00Z'},{seq:2,kind:'pause',occurred_at:'2026-11-20T02:00:00Z'},{seq:3,kind:'resume',occurred_at:'2026-11-20T02:30:00Z'},{seq:4,kind:'end',occurred_at:'2026-11-20T04:30:00Z'}],locations:[],notes:[],cases:[],corrections:[]}}));
await page.reload();
await page.getByRole('heading',{name:'오늘의 현황'}).waitFor();
await page.screenshot({path:'docs/screenshots/admin-dashboard-test-fixture.png',fullPage:true});
await page.getByRole('button',{name:'기록 확인'}).click();
await page.getByRole('heading',{name:'테스트 이용자 · 방문 기록'}).waitFor();
assert.equal(await page.locator('dialog').isVisible(),true);
await page.screenshot({path:'docs/screenshots/admin-visit-test-fixture.png',fullPage:true});
await page.getByRole('button',{name:'닫기',exact:true}).click();
await page.getByRole('button',{name:'지원사·이용자',exact:true}).click();
await page.getByRole('heading',{name:'이용자 등록'}).waitFor();
await page.getByRole('button',{name:'일정',exact:true}).click();
await page.getByRole('heading',{name:'방문 일정 배정'}).waitFor();
await page.setViewportSize({width:390,height:844});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+2));
assert.deepEqual(errors,[]);
await browser.close();
console.log('PASS: login, dashboard, visit detail, staff/schedule navigation, small viewport, no JS exceptions (mock data; not remote integration).');
